"""Command line entry points: demo, eval, bench.

    PYTHONPATH=artifacts/2026-10-23-recon python -m recon.cli demo
    PYTHONPATH=artifacts/2026-10-23-recon python -m recon.cli eval
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

from .engine import Policy, reconcile
from .evals import clean_run, evaluate, to_markdown
from .inject import inject, make_clean
from .model import rows_to_csv

ARTIFACT = Path(__file__).resolve().parents[1]
RESULTS = ARTIFACT / "results"


def _demo(policy: Policy) -> None:
    clean = make_clean(seed=7, count=120)
    day = inject(clean, seed=11, per_class=4)
    result = reconcile(day.expectations, day.rows, policy)

    print(f"{len(day.expectations)} expected payments, {len(day.rows)} settlement lines")
    print(f"{len(result.matches)} matched, {len(result.breaks)} breaks\n")

    for brk in result.breaks:
        money = ", ".join(f"{amount} minor {currency}" for currency, amount in brk.contributions.items())
        print(f"[{brk.kind}] {brk.ref}: {brk.detail}  ({money})")

    print("\ninvariants")
    print(f"  every line accounted for: {'pass' if result.every_line_accounted() else 'FAIL'}")
    print(f"  residual explained:       {'pass' if result.balances() else 'FAIL'}")
    print(f"  residual:                 {result.residual()}")

    sample = ARTIFACT / "results" / "sample_settlement.csv"
    sample.parent.mkdir(parents=True, exist_ok=True)
    sample.write_text(rows_to_csv(day.rows[:40]))
    print(f"\nwrote {sample.relative_to(ARTIFACT)} (first 40 lines)")


def _eval(policy: Policy) -> None:
    clean = make_clean(seed=7, count=400)
    broken = inject(clean, seed=11, per_class=12)
    evaluation = evaluate(broken, policy)
    clean_stats = clean_run(clean, policy)

    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "eval.md").write_text(to_markdown(evaluation, clean_stats, policy))
    (RESULTS / "eval.json").write_text(json.dumps({
        "policy": {"tolerance_minor": policy.tolerance_minor,
                   "date_window_days": policy.date_window_days},
        "injected": {
            "expectations": evaluation["expectations"],
            "rows": evaluation["rows"],
            "matches": evaluation["matches"],
            "breaks": evaluation["breaks"],
            "micro_precision": round(evaluation["micro_precision"], 4),
            "micro_recall": round(evaluation["micro_recall"], 4),
            "micro_f1": round(evaluation["micro_f1"], 4),
            "accounted": evaluation["accounted"],
            "balances": evaluation["balances"],
            "per_class": [
                {"kind": s.kind, "injected": s.injected, "detected": s.detected,
                 "recall": round(s.recall, 4), "precision": round(s.precision, 4),
                 "f1": round(s.f1, 4)}
                for s in evaluation["classes"]
            ],
        },
        "clean": clean_stats,
    }, indent=2))

    print(to_markdown(evaluation, clean_stats, policy))
    print(f"wrote {RESULTS.relative_to(ARTIFACT)}/eval.md and eval.json")


def _bench(policy: Policy) -> None:
    clean = make_clean(seed=7, count=20_000)
    day = inject(clean, seed=11, per_class=100)
    start = time.perf_counter()
    result = reconcile(day.expectations, day.rows, policy)
    elapsed = time.perf_counter() - start
    rate = len(day.rows) / elapsed
    report = (
        "# Bench\n\n"
        "Generated by `python -m recon.cli bench` on a single core.\n\n"
        "| Lines | Expected payments | Time | Lines per second |\n"
        "|---|---|---|---|\n"
        f"| {len(day.rows):,} | {len(day.expectations):,} | {elapsed * 1000:.0f} ms | {rate:,.0f} |\n\n"
        f"Matched {len(result.matches):,}, breaks {len(result.breaks):,}, "
        f"accounted {result.every_line_accounted()}, balances {result.balances()}.\n"
    )
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "bench.md").write_text(report)
    print(report)
    print(f"wrote {RESULTS.relative_to(ARTIFACT)}/bench.md")


def main() -> None:
    ap = argparse.ArgumentParser(prog="recon")
    ap.add_argument("command", choices=["demo", "eval", "bench"])
    ap.add_argument("--tolerance", type=int, default=1)
    ap.add_argument("--window", type=int, default=3)
    args = ap.parse_args()

    policy = Policy(tolerance_minor=args.tolerance, date_window_days=args.window)
    {"demo": _demo, "eval": _eval, "bench": _bench}[args.command](policy)


if __name__ == "__main__":
    main()
