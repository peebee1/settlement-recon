"""Did the matcher find what was injected, and did it invent anything?

Per class: recall (found / injected) and precision (correct / claimed). Plus two hard
invariants on every run: every line accounted for exactly once, and the residual fully
explained.
"""

from __future__ import annotations

from dataclasses import dataclass

from .engine import Policy, reconcile
from .inject import BREAK_CLASSES, Day


@dataclass
class ClassScore:
    kind: str
    injected: int
    detected: int
    true_positives: int

    @property
    def recall(self) -> float:
        return self.true_positives / self.injected if self.injected else 1.0

    @property
    def precision(self) -> float:
        return self.true_positives / self.detected if self.detected else 1.0

    @property
    def f1(self) -> float:
        p, r = self.precision, self.recall
        return 2 * p * r / (p + r) if p + r else 0.0


def _detected(day: Day, policy: Policy) -> dict[str, set[str]]:
    result = reconcile(day.expectations, day.rows, policy)
    found: dict[str, set[str]] = {kind: set() for kind in BREAK_CLASSES}
    for brk in result.breaks:
        found.setdefault(brk.kind, set()).add(brk.ref)
    for match in result.matches:
        for flag in match.flags:
            found.setdefault(flag, set()).add(match.ref)
    return found


def evaluate(day: Day, policy: Policy | None = None) -> dict:
    policy = policy or Policy()
    result = reconcile(day.expectations, day.rows, policy)
    found = _detected(day, policy)

    scores = []
    for kind in BREAK_CLASSES:
        actual = set(day.truth.get(kind, set()))
        claimed = set(found.get(kind, set()))
        scores.append(ClassScore(
            kind=kind,
            injected=len(actual),
            detected=len(claimed),
            true_positives=len(actual & claimed),
        ))

    micro_tp = sum(s.true_positives for s in scores)
    micro_injected = sum(s.injected for s in scores)
    micro_detected = sum(s.detected for s in scores)
    micro_precision = micro_tp / micro_detected if micro_detected else 1.0
    micro_recall = micro_tp / micro_injected if micro_injected else 1.0
    explained = result.explained()
    unexplained = {
        currency: result.residual().get(currency, 0) - explained.get(currency, 0)
        for currency in set(result.residual()) | set(explained)
    }

    return {
        "classes": scores,
        "micro_precision": micro_precision,
        "micro_recall": micro_recall,
        "micro_f1": (2 * micro_precision * micro_recall / (micro_precision + micro_recall)
                     if micro_precision + micro_recall else 0.0),
        "rows": len(day.rows),
        "expectations": len(day.expectations),
        "breaks": len(result.breaks),
        "matches": len(result.matches),
        "balances": result.balances(),
        "accounted": result.every_line_accounted(),
        "residual": result.residual(),
        "unexplained": unexplained,
        "unexplained_total": sum(abs(v) for v in unexplained.values()),
    }


def clean_run(day: Day, policy: Policy | None = None) -> dict:
    """On a clean day the matcher must produce no breaks and account for every line."""
    policy = policy or Policy()
    result = reconcile(day.expectations, day.rows, policy)
    return {
        "breaks": len(result.breaks),
        "break_kinds": result.by_kind(),
        "flags": result.by_flag(),
        "balances": result.balances(),
        "accounted": result.every_line_accounted(),
        "matches": len(result.matches),
    }


def to_markdown(evaluation: dict, clean: dict, policy: Policy) -> str:
    lines = [
        "# Results",
        "",
        "Generated by `python -m recon.cli eval`. Every number below comes from this run.",
        "",
        f"Policy: tolerance {policy.tolerance_minor} minor unit, settlement window "
        f"{policy.date_window_days} days.",
        "",
        "## Injected breaks, by class",
        "",
        "| Class | Injected | Detected | Recall | Precision | F1 |",
        "|---|---|---|---|---|---|",
    ]
    for s in evaluation["classes"]:
        lines.append(
            f"| {s.kind} | {s.injected} | {s.detected} | {s.recall:.3f} | "
            f"{s.precision:.3f} | {s.f1:.3f} |"
        )
    lines += [
        "",
        f"Micro precision **{evaluation['micro_precision']:.3f}**, "
        f"micro recall **{evaluation['micro_recall']:.3f}**, "
        f"micro F1 **{evaluation['micro_f1']:.3f}**.",
        "",
        f"Day size: {evaluation['expectations']} expected payments, {evaluation['rows']} settlement rows, "
        f"{evaluation['matches']} matches, {evaluation['breaks']} breaks.",
        "",
        "## Invariants",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| Every line accounted for exactly once | {'pass' if evaluation['accounted'] else 'FAIL'} |",
        f"| Residual fully explained by matches and breaks | {'pass' if evaluation['balances'] else 'FAIL'} |",
        f"| Unexplained minor units, all currencies | {evaluation['unexplained_total']} |",
        "",
        "Residual is expected minus settled, per currency. With breaks injected it is not",
        "zero: the breaks are the explanation. What must be zero is the part no match and no",
        "break accounts for.",
        "",
        "| Currency | Residual (minor units) |",
        "|---|---|",
        *[f"| {currency} | {amount} |" for currency, amount in sorted(evaluation["residual"].items())],
        "",
        "## Clean day",
        "",
        "Same generator, no breaks injected. A matcher that invents breaks is worse than one that misses them.",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| Breaks raised | {clean['breaks']} |",
        f"| Lines accounted for | {'pass' if clean['accounted'] else 'FAIL'} |",
        f"| Residual explained | {'pass' if clean['balances'] else 'FAIL'} |",
        f"| Matches | {clean['matches']} |",
        f"| Informational flags | {clean['flags'] or 'none'} |",
        "",
        "## What these numbers mean",
        "",
        "The breaks are synthetic and the classes are known, so perfect recall here means the",
        "cascade has no blind spot on these six classes, not that it solves reconciliation in the",
        "wild. The clean day is the more useful number: it shows whether tolerance and splitting",
        "logic start inventing breaks.",
        "",
    ]
    return "\n".join(lines)
